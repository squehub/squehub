    private function page(): string
    {
        return self::header() . <<<'PHP'
use stdClass;

/**
 * @template T
 * The server's data/meta pagination shape, with hydrated data items.
 */
final readonly class Page
{
    /**
     * @param list<T> $data
     * @param array<string,mixed> $meta
     */
    public function __construct(public array $data, public array $meta)
    {
    }

    /**
     * @template U
     * @param callable(mixed):U $hydrate
     * @return self<U>
     */
    public static function fromValue(mixed $value, callable $hydrate): self
    {
        if (!$value instanceof stdClass || !isset($value->data, $value->meta)
            || !is_array($value->data) || !$value->meta instanceof stdClass) {
            throw new ProtocolException();
        }
        $meta = (array) $value->meta;
        foreach (['page', 'per_page', 'total', 'pages'] as $name) {
            if (!isset($meta[$name]) || !is_int($meta[$name])) throw new ProtocolException();
        }
        foreach (['from', 'to'] as $name) {
            if (!array_key_exists($name, $meta)
                || ($meta[$name] !== null && !is_int($meta[$name]))) throw new ProtocolException();
        }
        foreach (['has_next', 'has_previous'] as $name) {
            if (!isset($meta[$name]) || !is_bool($meta[$name])) throw new ProtocolException();
        }
        return new self(array_map($hydrate, $value->data), $meta);
    }
}
PHP
            . "\n";
    }

    private function shape(): string
    {
        return self::header() . <<<'PHP'
use stdClass;

/**
 * Bounded structural checking at the generated client boundary. It checks
 * declared types, required/nullable fields, references and compositions;
 * failures are intentionally generic so server values never enter exceptions.
 */
final class Shape
{
    /** Convert inline JSON objects without leaving nested stdClass values. */
    public static function toArray(mixed $value, int $depth = 0): array
    {
        if ($depth > 64 || (!is_array($value) && !$value instanceof stdClass)) {
            throw new ProtocolException();
        }
        $result = (array) $value;
        foreach ($result as $name => $child) {
            if (is_array($child) || $child instanceof stdClass) {
                $result[$name] = self::toArray($child, $depth + 1);
            }
        }
        return $result;
    }

    public static function matches(mixed $value, array|bool $schema): bool
    {
        try {
            self::assert($value, $schema);
            return true;
        } catch (ProtocolException) {
            return false;
        }
    }

    public static function assert(mixed $value, array|bool $schema, bool $response = true,
        int $depth = 0): void
    {
        if ($depth > 64 || $schema === false) throw new ProtocolException();
        if ($schema === true) return;
        if (isset($schema['$ref'])) {
            $name = substr((string) $schema['$ref'], strlen('#/components/schemas/'));
            $target = SchemaMap::SCHEMAS[$name] ?? null;
            if ($target === null) throw new ProtocolException();
            self::assert($value, $target, $response, $depth + 1);
            return;
        }
        foreach (['allOf', 'anyOf', 'oneOf'] as $composition) {
            if (!isset($schema[$composition])) continue;
            $matches = 0;
            foreach ($schema[$composition] as $part) {
                try {
                    self::assert($value, $part, $response, $depth + 1);
                    ++$matches;
                } catch (ProtocolException) {
                    // A failed branch is expected for union and intersection evaluation.
                }
            }
            if (($composition === 'allOf' && $matches !== count($schema[$composition]))
                || ($composition === 'anyOf' && $matches === 0)
                || ($composition === 'oneOf' && $matches !== 1)) {
                throw new ProtocolException();
            }
        }
        if (array_key_exists('const', $schema) && !self::sameJson($value, $schema['const'])) {
            throw new ProtocolException();
        }
        if (isset($schema['enum'])) {
            $matched = false;
            foreach ($schema['enum'] as $choice) {
                if (self::sameJson($value, $choice)) { $matched = true; break; }
            }
            if (!$matched) throw new ProtocolException();
        }
        $types = $schema['type'] ?? null;
        if ($types === null) return;
        $types = (array) $types;
        $actual = self::type($value);
        if (!in_array($actual, $types, true)
            && !($actual === 'integer' && in_array('number', $types, true))) {
            throw new ProtocolException();
        }
        if ($actual === 'object') {
            $object = $value instanceof stdClass ? (array) $value : $value;
            $properties = $schema['properties'] ?? [];
            foreach ($schema['required'] ?? [] as $name) {
                $property = $properties[$name] ?? [];
                if (($response && ($property['writeOnly'] ?? false))
                    || (!$response && ($property['readOnly'] ?? false))) continue;
                if (!array_key_exists($name, $object)) throw new ProtocolException();
            }
            foreach ($object as $name => $child) {
                if (array_key_exists($name, $properties)) {
                    $property = $properties[$name];
                    if (($response && ($property['writeOnly'] ?? false))
                        || (!$response && ($property['readOnly'] ?? false))) {
                        throw new ProtocolException();
                    }
                    self::assert($child, $property, $response, $depth + 1);
                } elseif (($schema['additionalProperties'] ?? true) === false) {
                    throw new ProtocolException();
                } elseif (is_array($schema['additionalProperties'] ?? null)
                    || is_bool($schema['additionalProperties'] ?? null)) {
                    self::assert($child, $schema['additionalProperties'], $response, $depth + 1);
                }
            }
        } elseif ($actual === 'array') {
            $count = count($value);
            if (isset($schema['minItems']) && $count < $schema['minItems']) throw new ProtocolException();
            if (isset($schema['maxItems']) && $count > $schema['maxItems']) throw new ProtocolException();
            foreach ($value as $child) {
                if (isset($schema['items'])) self::assert($child, $schema['items'], $response, $depth + 1);
            }
            if (($schema['uniqueItems'] ?? false) === true) {
                $encoded = array_map(static fn (mixed $item): string =>
                    json_encode($item, JSON_THROW_ON_ERROR), $value);
                if (count(array_unique($encoded)) !== $count) throw new ProtocolException();
            }
        } elseif ($actual === 'string') {
            if (isset($schema['minLength']) || isset($schema['maxLength'])) {
                $length = preg_match_all('/./us', $value);
                if ($length === false) throw new ProtocolException();
                if (isset($schema['minLength']) && $length < $schema['minLength']) throw new ProtocolException();
                if (isset($schema['maxLength']) && $length > $schema['maxLength']) throw new ProtocolException();
            }
            if (isset($schema['pattern'])) {
                $pattern = '~' . str_replace('~', '\~', $schema['pattern']) . '~u';
                if (@preg_match($pattern, $value) !== 1) throw new ProtocolException();
            }
        } elseif ($actual === 'integer' || $actual === 'number') {
            if (isset($schema['minimum']) && $value < $schema['minimum']) throw new ProtocolException();
            if (isset($schema['maximum']) && $value > $schema['maximum']) throw new ProtocolException();
            if (isset($schema['exclusiveMinimum']) && $value <= $schema['exclusiveMinimum']) throw new ProtocolException();
            if (isset($schema['exclusiveMaximum']) && $value >= $schema['exclusiveMaximum']) throw new ProtocolException();
        }
    }

    private static function type(mixed $value): string
    {
        return match (true) {
            $value === null => 'null',
            is_bool($value) => 'boolean',
            is_int($value) => 'integer',
            is_float($value) => 'number',
            is_string($value) => 'string',
            $value instanceof stdClass => 'object',
            is_array($value) && array_is_list($value) => 'array',
            is_array($value) => 'object',
            default => 'invalid',
        };
    }

    private static function sameJson(mixed $left, mixed $right): bool
    {
        try {
            return json_encode(self::canonical($left), JSON_THROW_ON_ERROR)
                === json_encode(self::canonical($right), JSON_THROW_ON_ERROR);
        } catch (\JsonException) {
            throw new ProtocolException();
        }
    }

    /** JSON object member order is insignificant for enum and const checks. */
    private static function canonical(mixed $value, int $depth = 0): mixed
    {
        if ($depth > 64) throw new ProtocolException();
        if ($value instanceof stdClass || (is_array($value) && !array_is_list($value))) {
            $properties = (array) $value;
            ksort($properties, SORT_STRING);
            $object = new stdClass();
            foreach ($properties as $name => $child) {
                $object->{(string) $name} = self::canonical($child, $depth + 1);
            }
            return $object;
        }
        if (is_array($value)) {
            return array_map(static fn (mixed $child): mixed => self::canonical($child, $depth + 1),
                $value);
        }
        return $value;
    }
}
