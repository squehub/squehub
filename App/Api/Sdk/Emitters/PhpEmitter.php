    private function curlTransport(): string
    {
        return self::header() . <<<'PHP'
/**
 * One cURL request per operation. Redirects are disabled so credentials are
 * never forwarded to a different origin by the generated transport.
 */
final class CurlTransport implements Transport
{
    public function send(string $method, string $url, array $headers, ?string $body): HttpResponse
    {
        if (!function_exists('curl_init')) throw new TransportException();
        $handle = curl_init($url);
        if ($handle === false) throw new TransportException();
        $responseHeaders = [];
        $headerLines = [];
        foreach ($headers as $name => $value) $headerLines[] = $name . ': ' . $value;
        try {
            $options = [
                CURLOPT_CUSTOMREQUEST => $method,
                CURLOPT_RETURNTRANSFER => true,
                CURLOPT_FOLLOWLOCATION => false,
                CURLOPT_CONNECTTIMEOUT => 10,
                CURLOPT_TIMEOUT => 30,
                CURLOPT_HTTPHEADER => $headerLines,
                CURLOPT_HEADERFUNCTION => static function ($unused, string $line) use (&$responseHeaders): int {
                    $length = strlen($line);
                    if (preg_match('/^HTTP\/\S+\s+[1-5][0-9]{2}/i', $line) === 1) {
                        $responseHeaders = [];
                    } else {
                        $colon = strpos($line, ':');
                        if ($colon !== false) {
                            $name = trim(substr($line, 0, $colon));
                            if ($name !== '') $responseHeaders[$name] = trim(substr($line, $colon + 1));
                        }
                    }
                    return $length;
                },
            ];
            if ($body !== null) $options[CURLOPT_POSTFIELDS] = $body;
            if (!curl_setopt_array($handle, $options)) throw new TransportException();
            $response = curl_exec($handle);
            if (!is_string($response)) throw new TransportException();
            $status = curl_getinfo($handle, CURLINFO_RESPONSE_CODE);
            if (!is_int($status) || $status < 100 || $status > 599) throw new TransportException();
            return new HttpResponse($status, $responseHeaders, $response);
        } finally {
            curl_close($handle);
        }
    }
}
PHP
            . "\n";
    }

