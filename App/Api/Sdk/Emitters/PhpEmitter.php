    private function runtime(): string
    {
        return self::header() . <<<'PHP'
use JsonException;
use stdClass;

/** Shared request and response mechanics; public methods remain operation-specific. */
final class Runtime
{
    private readonly string $baseUrl;

    /** @param callable():string|null $tokenProvider
     *  @param callable():string|null $sessionCookieProvider
     *  @param callable():string|null $csrfTokenProvider
     */
    public function __construct(
        string $baseUrl,
        private readonly Transport $transport,
        private readonly mixed $tokenProvider,
        private readonly mixed $sessionCookieProvider,
        private readonly mixed $csrfTokenProvider,
        private readonly string $csrfHeader,
    ) {
        $parts = parse_url($baseUrl);
        if ($parts === false || !in_array(strtolower($parts['scheme'] ?? ''), ['http', 'https'], true)
            || !isset($parts['host']) || isset($parts['user']) || isset($parts['pass'])
            || isset($parts['query']) || isset($parts['fragment'])) {
            throw new ProtocolException('The API base URL is invalid.');
        }
        if (!self::headerName($csrfHeader)) throw new ProtocolException('The CSRF header name is invalid.');
        $this->baseUrl = rtrim($baseUrl, '/');
    }

    /** @param array<string,mixed> $spec @param array<string,mixed> $args */
    public function send(array $spec, array $args): HttpResult
    {
        foreach (array_keys($args) as $key) {
            if (!in_array($key, ['path', 'query', 'headers', 'body'], true)) {
                throw new ProtocolException('An API argument group is unknown.');
            }
        }
        $path = $spec['path'];
        $query = [];
        $headers = ['Accept' => $spec['accept']];
        foreach (['path' => 'path_params', 'query' => 'query', 'headers' => 'headers'] as $group => $specKey) {
            $values = $args[$group] ?? [];
            if (!is_array($values)) throw new ProtocolException('API arguments must be keyed arrays.');
            $known = array_column($spec[$specKey], 'name');
            foreach ($values as $name => $unused) {
                if (!in_array($name, $known, true)) throw new ProtocolException('An API parameter is undeclared.');
            }
            foreach ($spec[$specKey] as $parameter) {
                $name = $parameter['name'];
                $present = array_key_exists($name, $values);
                if (!$present && array_key_exists('fixed', $parameter)) {
                    $value = $parameter['fixed'];
                    $present = true;
                } else {
                    $value = $present ? $values[$name] : null;
                }
                if (!$present) {
                    if ($parameter['required']) throw new ProtocolException('A required API parameter is missing.');
                    continue;
                }
                if (array_key_exists('fixed', $parameter) && $value !== $parameter['fixed']) {
                    throw new ProtocolException('An API version/header value conflicts with the contract.');
                }
                Shape::assert($value, $parameter['schema'], false);
                if (!is_scalar($value) || $value === '') throw new ProtocolException('An API parameter is not serializable.');
                $text = is_bool($value) ? ($value ? 'true' : 'false') : (string) $value;
                if ($group === 'path') {
                    // Mirror RouteMatcher's decoded-segment safety boundary.
                    if (in_array($text, ['.', '..'], true) || str_contains($text, '/')
                        || str_contains($text, '\\')
                        || preg_match('/[\x00-\x1F\x7F]/', $text) === 1) {
                        throw new ProtocolException('An API path parameter is unsafe.');
                    }
                    $path = str_replace('{' . $name . '}', rawurlencode($text), $path);
                } elseif ($group === 'query') {
                    $query[$name] = $text;
                } else {
                    if (!self::headerName($name) || !self::headerValue($text)) {
                        throw new ProtocolException('An API header is invalid.');
                    }
                    $headers[$name] = $text;
                }
            }
        }
        if (str_contains($path, '{') || str_contains($path, '}')) throw new ProtocolException();
        $url = $this->baseUrl . $path;
        if ($query !== []) $url .= '?' . http_build_query($query, '', '&', PHP_QUERY_RFC3986);
        if (strlen($url) > 16384) throw new ProtocolException('The API URL is too long.');

        $security = $spec['security'];
        if ($security === 'pat') {
            if ($this->tokenProvider !== null) {
                $token = self::resolveCredential($this->tokenProvider);
                if ($token !== null) {
                    if (!is_string($token) || $token === '' || !self::headerValue($token)
                        || preg_match('/\s/', $token) === 1) {
                        throw new ProtocolException('A PAT provider returned an invalid token.');
                    }
                    $headers['Authorization'] = 'Bearer ' . $token;
                }
            }
        } elseif ($security === 'session') {
            if ($this->sessionCookieProvider !== null) {
                $cookie = self::resolveCredential($this->sessionCookieProvider);
                if ($cookie !== null) {
                    if (!is_string($cookie) || $cookie === '' || !self::headerValue($cookie)) {
                        throw new ProtocolException('A Session cookie provider returned an invalid value.');
                    }
                    $headers['Cookie'] = $cookie;
                }
            }
            if (!in_array($spec['method'], ['GET', 'HEAD', 'OPTIONS'], true)
                && $this->csrfTokenProvider !== null) {
                $csrf = self::resolveCredential($this->csrfTokenProvider);
                if ($csrf !== null) {
                    if (!is_string($csrf) || $csrf === '' || !self::headerValue($csrf)) {
                        throw new ProtocolException('A CSRF token provider returned an invalid value.');
                    }
                    $headers[$this->csrfHeader] = $csrf;
                }
            }
        } elseif ($security !== 'none') {
            throw new ProtocolException();
        }

        $body = null;
        if ($spec['body']) {
            if (!array_key_exists('body', $args)) {
                if ($spec['body_required']) throw new ProtocolException('A required API body is missing.');
            } else {
                Shape::assert($args['body'], $spec['body_schema'], false);
                try {
                    $body = json_encode($args['body'], JSON_THROW_ON_ERROR
                        | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
                } catch (JsonException) {
                    throw new ProtocolException('The API body is not JSON serializable.');
                }
                $headers['Content-Type'] = $spec['request_content_type'];
            }
        } elseif (array_key_exists('body', $args)) {
            throw new ProtocolException('This API operation does not declare a body.');
        }

        try {
            $response = $this->transport->send($spec['method'], $url, $headers, $body);
        } catch (\Throwable) {
            // A custom transport must not leak its URL or credential-bearing error text.
            throw new TransportException();
        }
        if ($response->status < 200 || $response->status > 299) {
            $this->throwApiError($response);
        }
        if (!isset($spec['success'][$response->status])) {
            throw new ProtocolException('The API returned an undeclared success status.');
        }
        $declared = $spec['success'][$response->status];
        if ($declared['schema'] === null) return new HttpResult($response->status, null);
        if (!self::declaredJsonMediaType($response->header('Content-Type'),
            $declared['content_type'])) throw new ProtocolException();
        $data = self::decodeJson($response->body);
        Shape::assert($data, $declared['schema']);
        return new HttpResult($response->status, $data);
    }

    private function throwApiError(HttpResponse $response): never
    {
        if (!self::jsonMediaType($response->header('Content-Type'))) throw new ProtocolException();
        $payload = self::decodeJson($response->body);
        if (!$payload instanceof stdClass || !isset($payload->error, $payload->request_id)
            || !$payload->error instanceof stdClass
            || !is_string($payload->error->code ?? null)
            || !is_string($payload->error->message ?? null)
            || !is_string($payload->request_id)) {
            throw new ProtocolException();
        }
        $safeHeaders = [];
        foreach (['Retry-After', 'X-RateLimit-Limit', 'X-RateLimit-Remaining',
            'X-RateLimit-Reset'] as $name) {
            $value = $response->header($name);
            if ($value !== null && preg_match('/\A[0-9]{1,20}\z/D', $value) === 1) {
                $safeHeaders[$name] = $value;
            }
        }
        throw new ApiException($response->status,
            substr($payload->error->code, 0, 128),
            substr($payload->error->message, 0, 1024),
            isset($payload->error->details)
                ? Shape::toArray($payload->error->details) : null,
            substr($payload->request_id, 0, 128),
            $safeHeaders);
    }

    private static function decodeJson(string $body): mixed
    {
        try {
            return json_decode($body, false, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            throw new ProtocolException();
        }
    }

    private static function resolveCredential(mixed $provider): mixed
    {
        try {
            return $provider();
        } catch (\Throwable) {
            throw new ProtocolException('A runtime credential could not be resolved.');
        }
    }

    private static function jsonMediaType(?string $value): bool
    {
        if ($value === null) return false;
        $type = strtolower(trim(explode(';', $value, 2)[0]));
        return $type === 'application/json'
            || preg_match('~^application/[a-z0-9!#$&^_.+-]+\+json$~', $type) === 1;
    }

    private static function declaredJsonMediaType(?string $actual, ?string $expected): bool
    {
        if (!self::jsonMediaType($actual) || $expected === null) return false;
        return strtolower(trim(explode(';', $actual, 2)[0]))
            === strtolower(trim(explode(';', $expected, 2)[0]));
    }

    private static function headerName(string $name): bool
    {
        return preg_match("/\A[A-Za-z0-9!#$%&'*+.^_\x60|~-]{1,128}\z/D", $name) === 1;
    }

    private static function headerValue(string $value): bool
    {
        return strlen($value) <= 8192 && preg_match('/[\x00-\x1F\x7F]/', $value) !== 1;
    }
