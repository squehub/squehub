<?php

declare(strict_types=1);

namespace App\Api\Sdk\Emitters;

use App\Api\Sdk\SdkException;
use App\Api\Sdk\SdkModel;

/**
 * Emits a standalone PHP 8.2 client from the validated SqueHub SDK model.
 * Generated sources have no framework dependency and receive credentials only
 * at runtime. The output map is deterministic and contains no machine state.
 */
final class PhpEmitter
{
    private const MARKER = '// Generated by SqueHub. Do not edit directly.';
    private const NAMESPACE = 'SqueHubGenerated';
    private const PHP_RESERVED = [
        'abstract', 'and', 'array', 'as', 'break', 'callable', 'case', 'catch',
        'class', 'clone', 'const', 'continue', 'declare', 'default', 'do', 'echo',
        'else', 'elseif', 'empty', 'enddeclare', 'endfor', 'endforeach', 'endif',
        'endswitch', 'endwhile', 'enum', 'eval', 'exit', 'extends', 'false', 'final',
        'finally', 'fn', 'for', 'foreach', 'function', 'global', 'goto', 'if',
        'implements', 'include', 'instanceof', 'insteadof', 'interface', 'isset',
        'list', 'match', 'namespace', 'new', 'null', 'or', 'parent', 'print',
        'private', 'protected', 'public', 'readonly', 'require', 'return', 'self',
        'static', 'switch', 'throw', 'trait', 'true', 'try', 'unset', 'use', 'var',
        'while', 'xor', 'yield',
    ];

    /** @return array<string,string> Relative file names and complete source bytes. */
    public function emit(SdkModel $model): array
    {
        $files = [
            'autoload.php' => $this->autoload(),
            'composer.json' => $this->composer(),
            'src/ApiException.php' => $this->apiException(),
            'src/Client.php' => $this->client($model),
            'src/CurlTransport.php' => $this->curlTransport(),
            'src/HttpResponse.php' => $this->httpResponse(),
            'src/HttpResult.php' => $this->httpResult(),
            'src/Page.php' => $this->page(),
            'src/ProtocolException.php' => $this->protocolException(),
            'src/Runtime.php' => $this->runtime(),
            'src/SchemaMap.php' => $this->schemaMap($model),
            'src/Shape.php' => $this->shape(),
            'src/Transport.php' => $this->transport(),
            'src/TransportException.php' => $this->transportException(),
        ];
        $seen = [];
        foreach ($model->schemas as $name => $schema) {
            $symbol = $model->schemaSymbols[$name];
            if (!$this->isDto($schema)) continue;
            if (in_array(strtolower($symbol), self::PHP_RESERVED, true)) {
                throw new SdkException('Schema ' . $name . ' is a reserved PHP class name.');
            }
            if (isset($seen[strtolower($symbol)])) {
                throw new SdkException('Generated PHP model names collide.');
            }
            $seen[strtolower($symbol)] = true;
            $files['src/Model/' . $symbol . '.php'] = $this->dto($name, $schema, $model);
        }
        ksort($files, SORT_STRING);
        return $files;
    }

    private static function header(string $namespace = self::NAMESPACE): string
    {
        return "<?php\n" . self::MARKER . "\n\ndeclare(strict_types=1);\n\nnamespace "
            . $namespace . ";\n\n";
    }

    private static function literal(mixed $value): string
    {
        return var_export($value, true);
    }

    private function composer(): string
    {
        return "{\n"
            . "  \"name\": \"squehub/generated-sdk\",\n"
            . "  \"description\": \"Generated client for a SqueHub application API\",\n"
            . "  \"type\": \"library\",\n"
            . "  \"require\": {\"php\": \"^8.2\"},\n"
            . "  \"autoload\": {\"psr-4\": {\"SqueHubGenerated\\\\\": \"src/\"}}\n"
            . "}\n";
    }

    private function autoload(): string
    {
        return "<?php\n" . self::MARKER . "\n\ndeclare(strict_types=1);\n\n"
            . <<<'PHP'
spl_autoload_register(static function (string $class): void {
    $prefix = 'SqueHubGenerated\\';
    if (!str_starts_with($class, $prefix)) return;
    $relative = substr($class, strlen($prefix));
    if ($relative === '' || str_contains($relative, '..')) return;
    $file = __DIR__ . '/src/' . str_replace('\\', '/', $relative) . '.php';
    if (is_file($file)) require $file;
});
PHP
            . "\n";
    }

    private function schemaMap(SdkModel $model): string
    {
        return self::header() . "/** Named public schemas from this generated contract. */\n"
            . "final class SchemaMap\n{\n"
            . "    public const SCHEMAS = " . self::literal($model->schemas) . ";\n"
            . "}\n";
    }

    /** @param array<string,mixed>|bool $schema */
    private function isDto(array|bool $schema): bool
    {
        return is_array($schema) && !$this->isPage($schema)
            && ($schema['type'] ?? null) === 'object'
            && isset($schema['properties']) && is_array($schema['properties']);
    }

    /** @param array<string,mixed> $operation */
    private function operationSpec(array $operation): array
    {
        $groups = ['path' => [], 'query' => [], 'header' => []];
        foreach ($operation['parameters'] as $parameter) {
            $entry = ['name' => $parameter['name'], 'required' => $parameter['required'],
                'schema' => $parameter['schema']];
            if (is_array($parameter['schema']) && array_key_exists('const', $parameter['schema'])) {
                $entry['fixed'] = $parameter['schema']['const'];
            }
            $groups[$parameter['in']][] = $entry;
        }
        $success = [];
        foreach ($operation['responses'] as $status => $response) {
            if ((int) $status < 200 || (int) $status > 299) continue;
            $success[(int) $status] = [
                'schema' => $response['schema'], 'content_type' => $response['content_type'],
            ];
        }
        ksort($success, SORT_NUMERIC);
        $accepted = [];
        foreach ($success as $response) {
            $mediaType = $response['content_type'];
            if ($mediaType !== null) $accepted[strtolower($mediaType)] = $mediaType;
        }
        $accepted['application/json'] = 'application/json';
        return [
            'method' => $operation['method'], 'path' => $operation['path'],
            'security' => $operation['security']['type'],
            'accept' => implode(', ', array_values($accepted)),
            'path_params' => $groups['path'], 'query' => $groups['query'],
            'headers' => $groups['header'],
            'body' => $operation['request_body'] !== null,
            'body_required' => $operation['request_body']['required'] ?? false,
            'body_schema' => $operation['request_body']['schema'] ?? null,
            'request_content_type' => $operation['request_body']['content_type'] ?? null,
            'success' => $success,
        ];
    }

    private function client(SdkModel $model): string
    {
        $lines = [self::header(), "/** Public methods map one-to-one to stable operation IDs. */",
            'final class Client', '{', '    private Runtime $runtime;', '',
            '    /** Runtime credentials are never generated into source files. */',
            '    public function __construct(string $baseUrl, ?Transport $transport = null,',
            '        ?callable $tokenProvider = null, ?callable $sessionCookieProvider = null,',
            "        ?callable \$csrfTokenProvider = null, string \$csrfHeader = 'X-CSRF-Token')",
            '    {',
            '        $this->runtime = new Runtime($baseUrl, $transport ?? new CurlTransport(),',
            '            $tokenProvider, $sessionCookieProvider, $csrfTokenProvider, $csrfHeader);',
            '    }'];
        foreach ($model->operations as $operation) {
            $symbol = $operation['symbol'];
            $method = lcfirst($symbol);
            if (in_array(strtolower($method), self::PHP_RESERVED, true)) {
                throw new SdkException('Operation ' . $operation['operation_id']
                    . ' cannot be a PHP method name.');
            }
            $spec = $this->operationSpec($operation);
            $types = [];
            $expressions = [];
            foreach ($spec['success'] as $status => $response) {
                if ($response['schema'] === null) {
                    $types[] = 'null';
                    $expressions[$status] = 'null';
                } else {
                    $types[] = $this->nativeType($response['schema'], $model);
                    $expressions[$status] = $this->hydrate('$result->data', $response['schema'], $model);
                }
            }
            $native = $this->unionType($types);
            $void = $native === 'null';
            $doc = implode('|', array_unique(array_map(fn (array $r): string =>
                $r['schema'] === null ? ($void ? 'void' : 'null')
                    : $this->docType($r['schema'], $model),
                $spec['success'])));
            $lines[] = '';
            $lines[] = '    /**';
            $lines[] = '     * ' . $operation['operation_id'] . ' (' . $operation['method']
                . ' ' . $operation['path'] . ').';
            $lines[] = '     * @param array{path?:array<string,mixed>,query?:array<string,mixed>,'
                . 'headers?:array<string,mixed>,body?:mixed} $args';
            $lines[] = '     * @return ' . $doc;
            $lines[] = '     */';
            $lines[] = '    public function ' . $method . '(array $args = []): ' . ($void ? 'void' : $native);
            $lines[] = '    {';
            $lines[] = '        $result = $this->runtime->send(' . self::literal($spec) . ', $args);';
            if (!$void) {
                $lines[] = '        return match ($result->status) {';
                foreach ($expressions as $status => $expression) {
                    $lines[] = '            ' . $status . ' => ' . $expression . ',';
                }
                $lines[] = "            default => throw new ProtocolException('The API returned an undeclared success status.'),";
                $lines[] = '        };';
            }
            $lines[] = '    }';
        }
        $lines[] = '}';
        return implode("\n", $lines) . "\n";
    }

    /** @param array<string,mixed>|bool $schema */
    private function hydrate(string $expression, array|bool $schema, SdkModel $model,
        array $trail = []): string
    {
        if (!is_array($schema)) return $expression;
        if (isset($schema['$ref'])) {
            $name = substr($schema['$ref'], strlen('#/components/schemas/'));
            if (isset($trail[$name])) return $expression;
            $trail[$name] = true;
            if ($this->isPage($model->schemas[$name])) {
                return $this->hydrate($expression, $model->schemas[$name], $model, $trail);
            }
            if ($this->isDto($model->schemas[$name])) {
                return '\\' . self::NAMESPACE . '\\Model\\'
                    . $model->schemaSymbols[$name] . '::fromValue(' . $expression . ')';
            }
            return $this->hydrate($expression, $model->schemas[$name], $model, $trail);
        }
        if (isset($schema['oneOf']) || isset($schema['anyOf'])) {
            $branches = $schema['oneOf'] ?? $schema['anyOf'];
            $result = "throw new ProtocolException()";
            foreach (array_reverse($branches) as $branch) {
                $result = '(Shape::matches(' . $expression . ', '
                    . self::literal($branch) . ') ? '
                    . $this->hydrate($expression, $branch, $model, $trail) . ' : ' . $result . ')';
            }
            return $result;
        }
        if (($schema['type'] ?? null) === 'array' && isset($schema['items'])) {
            $item = $this->hydrate('$item', $schema['items'], $model, $trail);
            if ($item !== '$item') {
                return 'array_map(static fn (mixed $item): mixed => ' . $item
                    . ', (array) ' . $expression . ')';
            }
        }
        if ($this->isPage($schema)) {
            $item = $this->hydrate('$item', $schema['properties']['data']['items'], $model, $trail);
            return 'Page::fromValue(' . $expression . ', static fn (mixed $item): mixed => '
                . $item . ')';
        }
        if (($schema['type'] ?? null) === 'object') {
            // Inline objects remain associative values; named schemas alone
            // receive a stable DTO class in the generated package.
            return 'Shape::toArray(' . $expression . ')';
        }
        if (is_array($schema['type'] ?? null)
            && in_array('object', $schema['type'], true)) {
            return '(' . $expression . ' instanceof \\stdClass ? Shape::toArray('
                . $expression . ') : ' . $expression . ')';
        }
        return $expression;
    }

    private function isPage(array $schema): bool
    {
        $required = $schema['required'] ?? [];
        sort($required, SORT_STRING);
        return ($schema['type'] ?? null) === 'object'
            && array_keys($schema['properties'] ?? []) === ['data', 'meta']
            && $required === ['data', 'meta']
            && (($schema['properties']['data']['type'] ?? null) === 'array')
            && isset($schema['properties']['data']['items'])
            && (($schema['properties']['meta']['$ref'] ?? null)
                === '#/components/schemas/SqueHubPaginationMeta');
    }

    /** @param array<string,mixed>|bool $schema */
    private function nativeType(array|bool $schema, SdkModel $model, array $trail = []): string
    {
        if (is_bool($schema)) return 'mixed';
        if (isset($schema['$ref'])) {
            $name = substr($schema['$ref'], strlen('#/components/schemas/'));
            if (isset($trail[$name])) return 'mixed';
            $trail[$name] = true;
            if ($this->isPage($model->schemas[$name])) return 'Page';
            return $this->isDto($model->schemas[$name])
                ? 'Model\\' . $model->schemaSymbols[$name]
                : $this->nativeType($model->schemas[$name], $model, $trail);
        }
        if ($this->isPage($schema)) return 'Page';
        if (isset($schema['oneOf']) || isset($schema['anyOf'])) {
            $parts = $schema['oneOf'] ?? $schema['anyOf'];
            return $this->unionType(array_map(fn ($part): string => $this->nativeType($part, $model, $trail),
                $parts));
        }
        if (isset($schema['allOf'])) return 'mixed';
        $types = $schema['type'] ?? null;
        if ($types === null && isset($schema['enum'])) {
            $types = array_values(array_unique(array_map(static fn ($v): string => get_debug_type($v),
                $schema['enum'])));
        }
        if ($types === null) return 'mixed';
        $parts = [];
        foreach ((array) $types as $type) {
            $parts[] = match ($type) {
                'string' => 'string', 'integer', 'int' => 'int',
                'number', 'float' => 'float', 'boolean', 'bool' => 'bool',
                'array', 'object' => 'array', 'null' => 'null', default => 'mixed',
            };
        }
        return $this->unionType($parts);
    }

    /** @param array<string,mixed>|bool $schema */
    private function docType(array|bool $schema, SdkModel $model, array $trail = []): string
    {
        if (!is_array($schema)) return 'mixed';
        if (isset($schema['$ref'])) {
            $name = substr($schema['$ref'], strlen('#/components/schemas/'));
            if (isset($trail[$name])) return 'mixed';
            $trail[$name] = true;
            if ($this->isPage($model->schemas[$name])) {
                return $this->docType($model->schemas[$name], $model, $trail);
            }
            return $this->isDto($model->schemas[$name])
                ? 'Model\\' . $model->schemaSymbols[$name]
                : $this->docType($model->schemas[$name], $model, $trail);
        }
        if ($this->isPage($schema)) {
            return 'Page<' . $this->docType($schema['properties']['data']['items'], $model, $trail) . '>';
        }
        if (($schema['type'] ?? null) === 'array') {
            return 'list<' . $this->docType($schema['items'] ?? true, $model, $trail) . '>';
        }
        if (($schema['type'] ?? null) === 'object') return 'array<string,mixed>';
        return $this->nativeType($schema, $model);
    }

    /** @param list<string> $types */
    private function unionType(array $types): string
    {
        $types = array_values(array_unique(array_merge(...array_map(
            static fn (string $type): array => explode('|', $type), $types))));
        if (in_array('mixed', $types, true)) return 'mixed';
        if (in_array('float', $types, true) && in_array('int', $types, true)) {
            $types = array_values(array_diff($types, ['int']));
        }
        sort($types, SORT_STRING);
        return implode('|', $types);
    }

    private function transport(): string
    {
        return self::header() . <<<'PHP'
/** A small HTTP boundary so consumers can substitute their own transport. */
