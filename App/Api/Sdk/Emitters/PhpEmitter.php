    /** @param array<string,mixed> $schema */
    private function dto(string $name, array $schema, SdkModel $model): string
    {
        $symbol = $model->schemaSymbols[$name];
        $lines = [self::header(self::NAMESPACE . '\\Model'),
            'use ' . self::NAMESPACE . '\\ProtocolException;',
            'use ' . self::NAMESPACE . '\\Shape;',
            'use ' . self::NAMESPACE . '\\Page;',
            'use stdClass;', '',
            '/** Validated response value for the named ' . $name . ' schema. */',
            'final readonly class ' . $symbol,
            '{',
            '    private function __construct(private stdClass $data) {}',
            '',
            '    public static function fromValue(mixed $value): self',
            '    {',
            '        Shape::assert($value, ' . self::literal(['$ref' =>
                '#/components/schemas/' . $name]) . ');',
            '        if (!$value instanceof stdClass) throw new ProtocolException();',
            '        return new self($value);',
            '    }',
            '',
            '    /** @return array<string,mixed> */',
            '    public function toArray(): array { return Shape::toArray($this->data); }',
        ];
        $seen = [];
        foreach ($schema['properties'] as $property => $definition) {
            if (($definition['writeOnly'] ?? false) === true) continue;
            $parts = preg_split('/[^A-Za-z0-9]+/', $property);
            $suffix = implode('', array_map('ucfirst', array_filter($parts,
                static fn (string $part): bool => $part !== '')));
            if ($suffix === '') throw new SdkException('Schema ' . $name
                . ' has a property without a PHP accessor name.');
            $folded = strtolower($suffix);
            if (isset($seen[$folded])) {
                throw new SdkException('Schema ' . $name . ' has colliding PHP property accessors.');
            }
            $seen[$folded] = true;
            $required = in_array($property, $schema['required'] ?? [], true);
            $type = $this->nativeType($definition, $model);
            if (!$required) $type = $this->unionType([$type, 'null']);
            $doc = $this->docType($definition, $model);
            if (!$required && !in_array('null', explode('|', $doc), true)) $doc .= '|null';
            $type = str_replace('Model\\', '\\' . self::NAMESPACE . '\\Model\\', $type);
            $doc = str_replace('Model\\', '\\' . self::NAMESPACE . '\\Model\\', $doc);
            $value = '$this->data->{' . self::literal($property) . '}';
            $hydrated = $this->hydrate($value, $definition, $model);
            $lines[] = '';
            $lines[] = '    /** @return ' . $doc . ' */';
            $lines[] = '    public function get' . $suffix . '(): ' . $type;
            $lines[] = '    {';
            $lines[] = '        return ' . ($required ? $hydrated
                : '$this->has' . $suffix . '() ? ' . $hydrated . ' : null') . ';';
            $lines[] = '    }';
            if (!$required) {
                $lines[] = '';
                $lines[] = '    /** Distinguishes an absent property from an explicit JSON null. */';
                $lines[] = '    public function has' . $suffix . '(): bool';
                $lines[] = '    {';
                $lines[] = '        return property_exists($this->data, ' . self::literal($property) . ');';
                $lines[] = '    }';
            }
        }
        $lines[] = '}';
        return implode("\n", $lines) . "\n";
    }
