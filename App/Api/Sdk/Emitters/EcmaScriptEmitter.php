function validateArguments(spec: OperationSpec, args: RequestArgs): void {
  if (args === null || typeof args !== "object" || Array.isArray(args)) {
    throw new SqueHubProtocolError("API arguments must be an object.");
  }
  for (const name of Object.keys(args)) {
    if (!["path", "query", "headers", "body"].includes(name)) {
      throw new SqueHubProtocolError("An API argument group is unknown.");
    }
  }
  const groups: readonly ["path" | "query" | "headers", readonly ParameterSpec[]][] = [
    ["path", spec.pathParams], ["query", spec.query], ["headers", spec.headers],
  ];
  for (const [name, parameters] of groups) {
    const values = args[name];
    if (values === undefined) continue;
    if (values === null || typeof values !== "object" || Array.isArray(values)
      || ![Object.prototype, null].includes(Object.getPrototypeOf(values))) {
      throw new SqueHubProtocolError("API parameters must be keyed objects.");
    }
    for (const key of Object.keys(values)) {
      const parameter = parameters.find(item => item.name === key);
      if (!parameter) throw new SqueHubProtocolError("An API parameter is undeclared.");
      if (parameter.fixed !== undefined && values[key] !== parameter.fixed) {
        throw new SqueHubProtocolError("An API parameter conflicts with the contract.");
      }
    }
  }
  if (!spec.body && Object.prototype.hasOwnProperty.call(args, "body")) {
    throw new SqueHubProtocolError("This API operation has no request body.");
  }
}

