    private function typeScriptRuntime(): string
    {
        return self::MARKER . "\n" . <<<'TS'
import { SqueHubApiError, SqueHubProtocolError, SqueHubTransportError } from "./errors.js";

export type TokenProvider = string | (() => string | null | undefined | Promise<string | null | undefined>);
export type ClientOptions = {
  baseUrl: string;
  fetch?: typeof globalThis.fetch;
  token?: TokenProvider;
  credentials?: RequestCredentials;
  csrfToken?: TokenProvider;
  csrfHeader?: string;
};
type Scalar = string | number | boolean;
type ParameterSpec = { name: string; required: boolean; fixed?: Scalar };
type SuccessSpec = { status: number; body: boolean; contentType: string | null };
export type OperationSpec = {
  method: string;
  path: string;
  security: "none" | "pat" | "session";
  pathParams: readonly ParameterSpec[];
  query: readonly ParameterSpec[];
  headers: readonly ParameterSpec[];
  body: boolean;
  bodyRequired: boolean;
  requestContentType: string | null;
  accept: string;
  success: readonly SuccessSpec[];
};
export type RequestArgs = {
  path?: Record<string, Scalar | undefined>;
  query?: Record<string, Scalar | undefined>;
  headers?: Record<string, Scalar | undefined>;
  body?: unknown;
};
export type Requester = (spec: OperationSpec, args?: RequestArgs) => Promise<unknown>;

const SAFE_RESPONSE_HEADERS = ["retry-after", "x-ratelimit-limit", "x-ratelimit-remaining",
  "x-ratelimit-reset", "x-request-id", "allow"] as const;
const HEADER_NAME = /^[!#$%&'*+.^_`|~0-9A-Za-z-]+$/;

function scalar(value: unknown): string {
  if (typeof value !== "string" && typeof value !== "number" && typeof value !== "boolean") {
    throw new SqueHubProtocolError("An API parameter must be a scalar value.");
  }
  if (typeof value === "number" && !Number.isFinite(value)) {
    throw new SqueHubProtocolError("An API number must be finite.");
  }
  return String(value);
}

function ownValue(group: Record<string, Scalar | undefined> | undefined, name: string): Scalar | undefined {
  return group && Object.prototype.hasOwnProperty.call(group, name) ? group[name] : undefined;
}

function headerValue(value: unknown): string {
  const result = scalar(value);
  if (/[\r\n\0]/.test(result)) throw new SqueHubProtocolError("An API header value is invalid.");
  return result;
}

function pathSegment(value: unknown): string {
  const segment = scalar(value);
  if (segment === "" || segment === "." || segment === ".."
    || /[\/\\\x00-\x1F\x7F]/.test(segment)) {
    throw new SqueHubProtocolError("A path parameter is not a valid route segment.");
  }
  try { return encodeURIComponent(segment); }
  catch { throw new SqueHubProtocolError("A path parameter cannot be encoded."); }
}

function jsonValue(value: unknown, seen: WeakSet<object>, depth = 0): void {
  if (depth > 64) throw new SqueHubProtocolError("The JSON request body is too deeply nested.");
  if (value === null || typeof value === "string" || typeof value === "boolean") return;
  if (typeof value === "number" && Number.isFinite(value)) return;
  if (Array.isArray(value)) {
    if (seen.has(value)) throw new SqueHubProtocolError("The JSON request body is cyclic.");
    seen.add(value);
    for (const item of value) jsonValue(item, seen, depth + 1);
    seen.delete(value);
    return;
  }
  if (typeof value === "object" && value !== null
    && (Object.getPrototypeOf(value) === Object.prototype || Object.getPrototypeOf(value) === null)) {
    if (seen.has(value)) throw new SqueHubProtocolError("The JSON request body is cyclic.");
    seen.add(value);
    // JSON.stringify omits absent object properties represented as undefined.
    // Arrays keep their stricter rule because undefined becomes a null slot.
    for (const item of Object.values(value)) {
      if (item !== undefined) jsonValue(item, seen, depth + 1);
    }
    seen.delete(value);
    return;
  }
  throw new SqueHubProtocolError("The request body must contain JSON values only.");
}

async function resolveToken(provider: TokenProvider | undefined): Promise<string | null> {
  let value: string | null | undefined;
  try { value = typeof provider === "function" ? await provider() : provider; }
  catch { throw new SqueHubProtocolError("A runtime credential could not be resolved."); }
  if (value === null || value === undefined) return null;
