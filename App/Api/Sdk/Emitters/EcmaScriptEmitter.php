<?php

declare(strict_types=1);

namespace App\Api\Sdk\Emitters;

use App\Api\Sdk\SdkModel;
use JsonException;
use LogicException;

/** Shared structured rendering for the two independent ES module targets. */
abstract class EcmaScriptEmitter
{
    private const MARKER = '// Generated by SqueHub. Do not edit directly.';

    /** @return array<string, string> */
    final protected function render(SdkModel $model, bool $typescript): array
    {
        $extension = $typescript ? 'ts' : 'js';
        $files = [
            'client.' . $extension => $this->client($model, $typescript),
            'types.' . $extension => $typescript ? $this->typeScriptTypes($model) : $this->javaScriptTypes($model),
            'errors.' . $extension => $typescript ? $this->typeScriptErrors() : $this->javaScriptErrors(),
            'runtime.' . $extension => $typescript ? $this->typeScriptRuntime() : $this->javaScriptRuntime(),
            'index.' . $extension => $this->index($model, $typescript),
        ];
        if (!$typescript) {
            $files['package.json'] = "{\n  \"type\": \"module\"\n}\n";
        }
        ksort($files, SORT_STRING);
        return $files;
    }

    private function client(SdkModel $model, bool $typescript): string
    {
        $lines = [self::MARKER];
        if ($typescript) {
            $lines[] = 'import { createRequester, type ClientOptions, type OperationSpec, type Requester } from "./runtime.js";';
            $imports = [];
            foreach ($model->operations as $operation) {
                $imports[] = $operation['symbol'] . 'Response';
                if ($this->hasArguments($operation)) $imports[] = $operation['symbol'] . 'Args';
            }
            if ($imports !== []) {
                sort($imports, SORT_STRING);
                $lines[] = 'import type { ' . implode(', ', $imports) . ' } from "./types.js";';
            }
        } else {
            $lines[] = 'import { createRequester } from "./runtime.js";';
        }
        $lines[] = '';

        foreach ($model->operations as $operation) {
            $name = $operation['symbol'];
            $spec = $this->operationSpec($operation);
            $declaration = 'const spec' . $name . ($typescript ? ': OperationSpec' : '')
                . ' = ' . self::json($spec) . ';';
            $lines[] = $declaration;
        }
        if ($model->operations !== []) $lines[] = '';

        if ($typescript) {
            $lines[] = 'export class SqueHubClient {';
            $lines[] = '  private readonly _requester: Requester;';
            $lines[] = '';
            $lines[] = '  constructor(options: ClientOptions) {';
            $lines[] = '    this._requester = createRequester(options);';
            $lines[] = '  }';
        } else {
            $lines[] = 'export class SqueHubClient {';
            $lines[] = '  /** @param {import("./runtime.js").ClientOptions} options */';
            $lines[] = '  constructor(options) {';
            $lines[] = '    this._requester = createRequester(options);';
        }

        $tree = $this->operationTree($model->operations);
        if ($typescript) {
            foreach ($tree as $segment => $node) {
                $lines[] = '';
                $lines[] = '  readonly ' . $segment . ' = ' . $this->renderNode($node, 2, true) . ';';
            }
            $lines[] = '}';
        } else {
            foreach ($tree as $segment => $node) {
                if (isset($node['operation'])) {
                    $lines[] = '    ' . $this->jsMethodAnnotation($node['operation']);
                }
                $lines[] = '    this.' . $segment . ' = ' . $this->renderNode($node, 2, false) . ';';
            }
            $lines[] = '  }';
            $lines[] = '}';
        }
        return implode("\n", $lines) . "\n";
    }

    /** @param list<array<string,mixed>> $operations @return array<string,mixed> */
    private function operationTree(array $operations): array
    {
        $tree = [];
        foreach ($operations as $operation) {
            $node =& $tree;
            foreach ($operation['segments'] as $segment) {
                if (!is_string($segment) || preg_match('/\A[A-Za-z_$][A-Za-z0-9_$]*\z/D', $segment) !== 1) {
                    throw new LogicException('SDK operation has an invalid JavaScript symbol.');
                }
                $node =& $node[$segment];
            }
            if ($node !== null) {
                throw new LogicException('SDK operation symbols collide.');
            }
            $node = ['operation' => $operation];
            unset($node);
        }
        ksort($tree, SORT_STRING);
        return $tree;
    }

    /** @param array<string,mixed> $node */
    private function renderNode(array $node, int $depth, bool $typescript): string
    {
        if (isset($node['operation'])) {
            $operation = $node['operation'];
            $name = $operation['symbol'];
            $hasArgs = $this->hasArguments($operation);
            $required = $this->hasRequiredArguments($operation);
            $argument = !$hasArgs ? '' : ($typescript ? 'args: ' . $name . 'Args' : 'args')
                . ($required ? '' : ' = {}');
            $result = $typescript ? ': Promise<' . $name . 'Response>' : '';
            $call = 'this._requester(spec' . $name . ', ' . ($hasArgs ? 'args' : '{}') . ')';
            if ($typescript) $call .= ' as Promise<' . $name . 'Response>';
            return '(' . $argument . ')' . $result . ' => ' . $call;
        }
        $indent = str_repeat('  ', $depth);
        $inside = str_repeat('  ', $depth + 1);
        $lines = ['Object.freeze({'];
        ksort($node, SORT_STRING);
        foreach ($node as $segment => $child) {
            if (!$typescript && isset($child['operation'])) {
                $lines[] = $inside . $this->jsMethodAnnotation($child['operation']);
            }
            $lines[] = $inside . $segment . ': ' . $this->renderNode($child, $depth + 1, $typescript) . ',';
        }
        $lines[] = $indent . '})';
        return implode("\n", $lines);
    }

    /** @param array<string,mixed> $operation */
    private function jsMethodAnnotation(array $operation): string
    {
        $name = $operation['symbol'];
        $argument = $this->hasArguments($operation)
            ? '(args' . ($this->hasRequiredArguments($operation) ? '' : '?')
                . ': import("./types.js").' . $name . 'Args)'
            : '()';
        return '/** @type {' . $argument . ' => Promise<import("./types.js").'
            . $name . 'Response>} */';
    }

    /** @param array<string,mixed> $operation @return array<string,mixed> */
    private function operationSpec(array $operation): array
    {
        $path = [];
        $query = [];
        $headers = [];
        foreach ($operation['parameters'] as $parameter) {
            $entry = ['name' => $parameter['name'], 'required' => $parameter['required']];
            if (is_array($parameter['schema']) && array_key_exists('const', $parameter['schema'])) {
                $entry['fixed'] = $parameter['schema']['const'];
            }
            switch ($parameter['in']) {
                case 'path': $path[] = $entry; break;
                case 'query': $query[] = $entry; break;
                case 'header': $headers[] = $entry; break;
                default: throw new LogicException('SDK parameter location is unsupported.');
            }
        }
        $success = [];
        foreach ($operation['responses'] as $status => $response) {
            if ((int) $status < 200 || (int) $status > 299) continue;
            $success[] = ['status' => (int) $status, 'body' => $response['schema'] !== null,
                'contentType' => $response['content_type']];
        }
        if ($success === []) {
            throw new LogicException('SDK operation has no declared success response.');
        }
        usort($success, static fn (array $a, array $b): int => $a['status'] <=> $b['status']);
        $accepted = [];
        foreach ($success as $response) {
            if ($response['contentType'] === null) continue;
            $mediaType = strtolower(trim(explode(';', $response['contentType'], 2)[0]));
            $accepted[$mediaType] = true;
        }
        unset($accepted['application/json']);
        ksort($accepted, SORT_STRING);
        $accept = implode(', ', [...array_keys($accepted), 'application/json']);
        return [
            'method' => $operation['method'],
            'path' => $operation['path'],
            'security' => $operation['security']['type'],
            'pathParams' => $path,
            'query' => $query,
            'headers' => $headers,
            'body' => $operation['request_body'] !== null,
            'bodyRequired' => $operation['request_body']['required'] ?? false,
            'requestContentType' => $operation['request_body']['content_type'] ?? null,
            'accept' => $accept,
            'success' => $success,
        ];
    }

    /** @param array<string,mixed> $operation */
    private function hasArguments(array $operation): bool
    {
        foreach ($operation['parameters'] as $parameter) {
            if (!is_array($parameter['schema']) || !array_key_exists('const', $parameter['schema'])) return true;
        }
        return $operation['request_body'] !== null;
    }

    /** @param array<string,mixed> $operation */
    private function hasRequiredArguments(array $operation): bool
    {
        foreach ($operation['parameters'] as $parameter) {
            if ($parameter['required'] && (!is_array($parameter['schema'])
                || !array_key_exists('const', $parameter['schema']))) return true;
        }
        return ($operation['request_body']['required'] ?? false) === true;
    }

    private function typeScriptTypes(SdkModel $model): string
    {
        $lines = [self::MARKER, ''];
        if (isset($model->schemaSymbols['SqueHubPaginationMeta'])) {
            $lines[] = 'export type SqueHubPage<T> = { data: T[]; meta: SqueHubPaginationMeta };';
            $lines[] = '';
        }
        foreach ($model->schemas as $name => $schema) {
            $symbol = $model->schemaSymbols[$name];
            $lines[] = 'export type ' . $symbol . ' = ' . $this->type($schema, $model, false) . ';';
            $lines[] = 'export type ' . $symbol . 'Input = ' . $this->type($schema, $model, true) . ';';
            $lines[] = '';
        }
        foreach ($model->operations as $operation) {
            $name = $operation['symbol'];
            if ($this->hasArguments($operation)) {
                $lines[] = 'export type ' . $name . 'Args = ' . $this->argsType($operation, $model) . ';';
            }
            $lines[] = 'export type ' . $name . 'Response = ' . $this->responseType($operation, $model) . ';';
            $lines[] = '';
        }
        return rtrim(implode("\n", $lines)) . "\n";
    }

    private function javaScriptTypes(SdkModel $model): string
    {
        $lines = [self::MARKER, ''];
        if (isset($model->schemaSymbols['SqueHubPaginationMeta'])) {
            $lines[] = '/** @template T @typedef {{data: T[], meta: SqueHubPaginationMeta}} SqueHubPage */';
            $lines[] = '';
        }
        foreach ($model->schemas as $name => $schema) {
            $symbol = $model->schemaSymbols[$name];
            foreach ([false, true] as $input) {
                $target = $symbol . ($input ? 'Input' : '');
                $lines[] = '/** @typedef {' . $this->jsdocType($schema, $model, $input) . '} ' . $target . ' */';
            }
            $lines[] = '';
        }
        foreach ($model->operations as $operation) {
            $name = $operation['symbol'];
            if ($this->hasArguments($operation)) {
                $lines[] = '/** @typedef {' . $this->argsType($operation, $model, true) . '} ' . $name . 'Args */';
            }
            $lines[] = '/** @typedef {' . $this->responseType($operation, $model, true) . '} '
                . $name . 'Response */';
            $lines[] = '';
        }
        $lines[] = 'export {};';
        return implode("\n", $lines) . "\n";
    }

    /** @param array<string,mixed> $operation */
    private function argsType(array $operation, SdkModel $model, bool $jsdoc = false): string
    {
        $groups = ['path' => [], 'query' => [], 'header' => []];
        $groupRequired = ['path' => false, 'query' => false, 'header' => false];
        foreach ($operation['parameters'] as $parameter) {
            if (is_array($parameter['schema']) && array_key_exists('const', $parameter['schema'])) continue;
            $location = $parameter['in'];
            $groups[$location][] = self::json($parameter['name']) . ($parameter['required'] ? '' : '?')
                . ': ' . ($jsdoc ? $this->jsdocType($parameter['schema'], $model, true)
                    : $this->type($parameter['schema'], $model, true));
            if ($parameter['required']) $groupRequired[$location] = true;
        }
        $fields = [];
        foreach (['path', 'query', 'header'] as $location) {
            if ($groups[$location] === []) continue;
            $property = $location === 'header' ? 'headers' : $location;
            $fields[] = $property . ($groupRequired[$location] ? '' : '?')
                . ': { ' . implode('; ', $groups[$location]) . ' }';
        }
        if ($operation['request_body'] !== null) {
            $fields[] = 'body' . ($operation['request_body']['required'] ? '' : '?') . ': '
                . ($jsdoc ? $this->jsdocType($operation['request_body']['schema'], $model, true)
                    : $this->type($operation['request_body']['schema'], $model, true));
        }
        return '{ ' . implode('; ', $fields) . ' }';
    }

    /** @param array<string,mixed> $operation */
    private function responseType(array $operation, SdkModel $model, bool $jsdoc = false): string
    {
        $types = [];
        foreach ($operation['responses'] as $status => $response) {
            if ((int) $status < 200 || (int) $status > 299) continue;
            $types[] = $response['schema'] === null ? ($jsdoc ? 'undefined' : 'void')
                : ($jsdoc ? $this->jsdocType($response['schema'], $model, false)
                    : $this->type($response['schema'], $model, false));
        }
        $types = array_values(array_unique($types));
        sort($types, SORT_STRING);
        return implode(' | ', $types);
    }

    /** @param array<string,mixed>|bool $schema */
    private function type(array|bool $schema, SdkModel $model, bool $input): string
    {
        if ($schema === true) return 'unknown';
        if ($schema === false) return 'never';
        if (isset($schema['$ref'])) {
            $name = substr($schema['$ref'], strlen('#/components/schemas/'));
            return $model->schemaSymbols[$name] . ($input ? 'Input' : '');
        }
        if (array_key_exists('const', $schema)) return self::json($schema['const']);
        if (isset($schema['enum'])) {
            $values = array_map(self::json(...), $schema['enum']);
            sort($values, SORT_STRING);
            return implode(' | ', $values);
        }
        foreach (['oneOf', 'anyOf', 'allOf'] as $composition) {
            if (!isset($schema[$composition])) continue;
            $parts = array_map(fn (array|bool $part): string => '(' . $this->type($part, $model, $input) . ')',
                $schema[$composition]);
            return implode($composition === 'allOf' ? ' & ' : ' | ', $parts);
        }
        $types = (array) ($schema['type'] ?? []);
        if ($types === []) return 'unknown';
        $parts = [];
        foreach ($types as $type) {
            $parts[] = match ($type) {
                'null' => 'null',
                'string' => 'string',
                'integer', 'number' => 'number',
                'boolean' => 'boolean',
                'array' => '(' . $this->type($schema['items'] ?? true, $model, $input) . ')[]',
                'object' => $this->pageItem($schema, $model, $input) !== null
                    ? 'SqueHubPage<' . $this->type($this->pageItem($schema, $model, $input), $model, false) . '>'
                    : $this->objectType($schema, $model, $input),
                default => throw new LogicException('SDK schema type is unsupported.'),
            };
        }
        $parts = array_values(array_unique($parts));
        return implode(' | ', $parts);
    }

    /** @param array<string,mixed> $schema @return array<string,mixed>|bool|null */
    private function pageItem(array $schema, SdkModel $model, bool $input): array|bool|null
    {
        if ($input || !isset($model->schemaSymbols['SqueHubPaginationMeta'])
            || ($schema['type'] ?? null) !== 'object'
            || array_keys($schema['properties'] ?? []) !== ['data', 'meta']
            || !isset($schema['properties']['data']['items'])
            || ($schema['properties']['data']['type'] ?? null) !== 'array'
            || ($schema['properties']['meta']['$ref'] ?? null)
                !== '#/components/schemas/SqueHubPaginationMeta') {
            return null;
        }
        $required = $schema['required'] ?? [];
        sort($required, SORT_STRING);
        return $required === ['data', 'meta'] ? $schema['properties']['data']['items'] : null;
    }

    /** @param array<string,mixed> $schema */
    private function objectType(array $schema, SdkModel $model, bool $input): string
    {
        $fields = [];
        $properties = $schema['properties'] ?? [];
        $required = $schema['required'] ?? [];
        foreach ($properties as $name => $property) {
            if ($input && ($property['readOnly'] ?? false)) continue;
            if (!$input && ($property['writeOnly'] ?? false)) continue;
            $fields[] = self::json($name) . (in_array($name, $required, true) ? '' : '?')
                . ': ' . $this->type($property, $model, $input);
        }
        $additional = $schema['additionalProperties'] ?? true;
        if ($additional !== false) {
            $extraType = $additional === true ? 'unknown' : $this->type($additional, $model, $input);
            if ($fields === []) return 'Record<string, ' . $extraType . '>';
            // Declared properties are JSON Schema exceptions to the additional
            // value constraint; a broad index preserves those legal objects.
            $fields[] = '[key: string]: unknown';
        }
        if ($fields === []) return 'Record<string, never>';
        return '{ ' . implode('; ', $fields) . ' }';
    }

    /** @param array<string,mixed>|bool $schema */
    private function jsdocType(array|bool $schema, SdkModel $model, bool $input): string
    {
        // TypeScript understands these type expressions in JSDoc. Rewriting
        // tokens as raw text would also rewrite quoted enum values and keys.
        // A literal comment terminator in a schema string must not escape the
        // JSDoc block and become executable JavaScript source.
        return str_replace('*/', '*\\u002F', $this->type($schema, $model, $input));
    }

    private function index(SdkModel $model, bool $typescript): string
    {
        $lines = [self::MARKER, 'export { SqueHubClient } from "./client.js";',
            'export { SqueHubApiError, SqueHubProtocolError, SqueHubTransportError } from "./errors.js";'];
        if ($typescript) {
            $lines[] = 'export type { ClientOptions, TokenProvider } from "./runtime.js";';
            $types = [];
            if (isset($model->schemaSymbols['SqueHubPaginationMeta'])) $types[] = 'SqueHubPage';
            foreach ($model->schemaSymbols as $name => $symbol) {
                $types[] = $symbol;
                $types[] = $symbol . 'Input';
            }
            foreach ($model->operations as $operation) {
                $types[] = $operation['symbol'] . 'Response';
                if ($this->hasArguments($operation)) $types[] = $operation['symbol'] . 'Args';
            }
            if ($types !== []) {
                sort($types, SORT_STRING);
                $lines[] = 'export type { ' . implode(', ', $types) . ' } from "./types.js";';
            }
        }
        return implode("\n", $lines) . "\n";
    }

    private static function json(mixed $value): string
    {
        try {
            return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES
                | JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT);
        } catch (JsonException $exception) {
            throw new LogicException('SDK source value could not be encoded.', 0, $exception);
        }
    }

